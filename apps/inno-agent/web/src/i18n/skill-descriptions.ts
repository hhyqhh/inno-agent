function localeKey(language: string): "zh" | "en" {
	return language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** Use existing AI-polished copy first, then newly generated background copy. */
export function getFriendlySkillName(name: string, language: string, generated?: SkillDisplayCopy): string {
	const names = localeKey(language) === "zh" ? ZH_CN_SKILL_NAMES : EN_SKILL_NAMES;
	return names[name as keyof typeof ZH_CN_SKILL_NAMES] ?? generated?.displayName[localeKey(language)] ?? name;
}

/** Returns an empty string only when a skill has not been polished yet. */
export function getFriendlySkillDescription(name: string, language: string, generated?: SkillDisplayCopy): string {
	const descriptions = localeKey(language) === "zh"
		? ZH_CN_SKILL_DESCRIPTIONS
		: EN_SKILL_DESCRIPTIONS;
	return descriptions[name as keyof typeof ZH_CN_SKILL_DESCRIPTIONS] ?? generated?.description[localeKey(language)] ?? "";
}
